def generate_analytics_excel(sheet_title: str, summary_metrics: dict, table_headers: list[str], table_data: list[list[str]]) -> io.BytesIO:
    """
    Generates styled Excel (.xlsx) workbook for analytics reporting.
    """
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = sheet_title[:30]

    header_font = Font(name='Segoe UI', size=11, bold=True, color='FFFFFF')
    header_fill = PatternFill(start_color='1E293B', end_color='1E293B', fill_type='solid')
    sub_fill = PatternFill(start_color='F1F5F9', end_color='F1F5F9', fill_type='solid')
    thin_border = Border(
        left=Side(style='thin', color='CBD5E1'),
        right=Side(style='thin', color='CBD5E1'),
        top=Side(style='thin', color='CBD5E1'),
        bottom=Side(style='thin', color='CBD5E1'),
    )

    current_row = 1

    # Title
    ws.cell(row=current_row, column=1, value=f"{_('University Task Management')} - {sheet_title}").font = Font(size=14, bold=True, color='0F172A')
    current_row += 2

    # Summary metrics
    if summary_metrics:
        ws.cell(row=current_row, column=1, value=_("Summary Key Metrics")).font = Font(size=11, bold=True)
        current_row += 1
        for k, v in summary_metrics.items():
            ws.cell(row=current_row, column=1, value=k).font = Font(bold=True)
            ws.cell(row=current_row, column=2, value=str(v))
            current_row += 1
        current_row += 1

    # Detailed table
    if table_headers and table_data:
        for col_idx, h in enumerate(table_headers, 1):
            cell = ws.cell(row=current_row, column=col_idx, value=h)
            cell.font = header_font
            cell.fill = header_fill
            cell.alignment = Alignment(horizontal='center', vertical='center')
        current_row += 1

        for row in table_data:
            for col_idx, val in enumerate(row, 1):
                cell = ws.cell(row=current_row, column=col_idx, value=val)
                cell.border = thin_border
                cell.alignment = Alignment(vertical='center')
            current_row += 1

    # Auto-adjust column widths
    for col in ws.columns:
        max_len = max(len(str(cell.value or '')) for cell in col)
        col_letter = openpyxl.utils.get_column_letter(col[0].column)
        ws.column_dimensions[col_letter].width = max(max_len + 4, 12)

    buffer = io.BytesIO()
    wb.save(buffer)
    buffer.seek(0)
    return buffer


