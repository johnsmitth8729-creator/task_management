def generate_analytics_pdf(report_title: str, subtitle: str, summary_metrics: dict, table_headers: list[str], table_data: list[list[str]], user_name: str) -> io.BytesIO:
    """
    Generates a university-branded executive analytics PDF report in English.
    """
    from django.utils.translation import override

    with override('en'):
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            leftMargin=36,
            rightMargin=36,
            topMargin=36,
            bottomMargin=36,
        )

        story = []
        styles = _get_pdf_styles()
        now_str = timezone.now().strftime('%Y-%m-%d %H:%M')

        # Header section
        logo_path = _get_logo_path()
        if logo_path and logo_path.exists():
            try:
                from PIL import Image as PILImage
                with PILImage.open(str(logo_path)) as pil_img:
                    orig_w, orig_h = pil_img.size
                aspect = (orig_w / orig_h) if orig_h else 1.0
                target_h = 0.65 * 72
                target_w = target_h * aspect
                logo_img = Image(str(logo_path), width=target_w, height=target_h)
                logo_img.hAlign = 'LEFT'
                story.append(logo_img)
                story.append(Spacer(1, 6))
            except Exception:
                pass

        story.append(Paragraph(f"<b>AL-KHWARIZMI UNIVERSITY</b> — ANALYTICS REPORT", styles['ReportSubHeader']))
        story.append(Paragraph(report_title, styles['ReportHeader']))
        story.append(Paragraph(f"{subtitle} | Generated by: {user_name} ({now_str})", styles['ReportSubHeader']))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#cbd5e1'), spaceBefore=2, spaceAfter=10))

        # Summary metrics grid
        if summary_metrics:
            story.append(Paragraph("Executive Summary Metrics", styles['SectionHeading']))
            summary_rows = []
            items = list(summary_metrics.items())
            for i in range(0, len(items), 2):
                row = []
                k1, v1 = items[i]
                row.extend([Paragraph(f"<b>{k1}:</b>", styles['BodyCell']), Paragraph(str(v1), styles['BodyCell'])])
                if i + 1 < len(items):
                    k2, v2 = items[i + 1]
                    row.extend([Paragraph(f"<b>{k2}:</b>", styles['BodyCell']), Paragraph(str(v2), styles['BodyCell'])])
                else:
                    row.extend(['', ''])
                summary_rows.append(row)

            summary_table = Table(summary_rows, colWidths=[120, 140, 120, 140])
            summary_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#f8fafc')),
                ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
                ('TOPPADDING', (0, 0), (-1, -1), 4),
                ('LEFTPADDING', (0, 0), (-1, -1), 6),
                ('RIGHTPADDING', (0, 0), (-1, -1), 6),
                ('LINEBELOW', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
            ]))
            story.append(summary_table)
            story.append(Spacer(1, 12))

        # Detailed Data Table
        if table_headers and table_data:
            story.append(Paragraph("Detailed Data", styles['SectionHeading']))
            header_row = [Paragraph(f"<b>{h}</b>", styles['HeaderCell']) for h in table_headers]
            data_rows = [[Paragraph(str(cell), styles['BodyCell']) for cell in row] for row in table_data]
            all_rows = [header_row] + data_rows

            col_w = 540 / len(table_headers)
            data_table = Table(all_rows, colWidths=[col_w] * len(table_headers))
            data_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#1e293b')),
                ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
                ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
                ('TOPPADDING', (0, 0), (-1, -1), 4),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
                ('LEFTPADDING', (0, 0), (-1, -1), 4),
                ('RIGHTPADDING', (0, 0), (-1, -1), 4),
                ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f8fafc')]),
                ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
            ]))
            story.append(data_table)

        # Footer
        story.append(Spacer(1, 14))
        story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor('#cbd5e1'), spaceBefore=4, spaceAfter=6))
        story.append(Paragraph(
            "Confidential — For authorized university management only. Data generated dynamically from official university databases.",
            ParagraphStyle('Footer', parent=styles['Normal'], fontSize=7.5, textColor=colors.HexColor('#94a3b8'), alignment=1)
        ))

        doc.build(story)
        buffer.seek(0)
        return buffer


