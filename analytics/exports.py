def generate_analytics_csv(table_headers: list[str], table_data: list[list[str]]) -> str:
    """
    Generates standard RFC-4180 CSV string for analytics reporting.
    """
    output = io.StringIO()
    writer = csv.writer(output)
    if table_headers:
        writer.writerow(table_headers)
    for row in table_data:
        writer.writerow(row)
    return output.getvalue()
